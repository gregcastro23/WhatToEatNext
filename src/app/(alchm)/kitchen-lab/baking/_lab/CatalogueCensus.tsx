"use client";

import { type JSX } from "react";
import { isSimulable, type CatalogueEntry } from "@/lib/baking/recipes/catalogue";
import { SKIP_REASON_TEXT, type SkipReason } from "@/lib/baking/recipes/selectSources";
import type { BakingCatalogue } from "./useBakingCatalogue";

/** Refusal reasons, grouped by what stopped the bake. */
const BUCKETS: ReadonlyArray<[RegExp, string]> = [
  [/^a (pastry|pie or tart|crust)/, "pastry, pie, tart or crust: several materials, refused by design"],
  [/^served with/, "served with a companion in one ingredient list"],
  [/^its structure/, "its flour, starch or dough has no vector"],
  [/^no flour or starch/, "no flour or starch that sets a crumb"],
  [/^the mass of/, "a line of unknown mass"],
  [/% of the recipe's mass/, "over 10 % of its mass unread"],
  [/^its computed/, "its shape is outside the simulator's range"],
];

const SKIP_ORDER: readonly SkipReason[] = ["no-structure-line", "not-a-baked-good"];

function bucketCounts(reasonsPerRecipe: ReadonlyArray<readonly string[]>): Array<[string, number]> {
  return BUCKETS.map(([pattern, label]): [string, number] => [label, reasonsPerRecipe.filter((rs) => rs.some((r) => pattern.test(r))).length]).filter(([, n]) => n > 0);
}

/** Where the catalogue came from and what it left out: every recipe is accounted for. */
export function CatalogueCensus({ catalogue }: { catalogue: BakingCatalogue }): JSX.Element {
  const { load, entries } = catalogue;
  if (load.status !== "ready") return <div className="bl-card text-sm text-white/55">{load.status === "loading" ? "Loading the recipe catalogue…" : `The recipe catalogue did not load: ${load.reason}`}</div>;
  const { file } = load;
  const recipes = entries.filter((e): e is Extract<CatalogueEntry, { kind: "recipe" }> => e.kind === "recipe");
  const refused = recipes.filter((e) => !isSimulable(e));
  const reasons = refused.map((e) => (e.converted.report.verdict.simulable ? [] : e.converted.report.verdict.reasons));
  const skippedBy = (reason: SkipReason): string[] => file.skipped.filter((s) => s.reason === reason).map((s) => s.name);
  const baked = file.servedRecipes - file.notBaked;
  return (
    <div className="bl-card">
      <h2 className="text-xl">The recipe catalogue</h2>
      <p className="mt-1 text-sm text-white/65">
        {file.servedRecipes} served recipes · {file.notBaked} not baked · {baked} baked → <strong>{file.sources.length} bakeable goods</strong> ({recipes.length - refused.length} simulable, {refused.length} shown with the reason they are refused) · {file.skipped.length} baked but not baked goods.
      </p>
      <p className="mt-1 text-[11px] text-white/40">Generated by {file.source}; a test rebuilds it from the served recipes and fails if it drifts.</p>
      <details className="bl-report mt-2">
        <summary>Why {refused.length} are refused (a recipe can have several reasons)</summary>
        <ul className="space-y-1 text-[12px]">
          {bucketCounts(reasons).map(([label, n]) => (
            <li key={label}>
              <span className="bl-num">{n}</span> — {label}
            </li>
          ))}
        </ul>
      </details>
      {SKIP_ORDER.map((reason) => (
        <details key={reason} className="bl-report">
          <summary>
            {skippedBy(reason).length} skipped: {SKIP_REASON_TEXT[reason]}
          </summary>
          <p className="text-[12px] text-white/55">{skippedBy(reason).join(" · ")}</p>
        </details>
      ))}
    </div>
  );
}
